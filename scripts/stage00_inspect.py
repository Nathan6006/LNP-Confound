"""
Stage 0 — Inspect and document the raw data.

Reads the four raw CSVs read-only from data/, profiles every column, resolves
the schema (which column plays which role in each dataset), confirms that
LNPDB_vitro + LNPDB_vivo is a clean partition of Original_LNPDB, and profiles
molea.csv's endpoint encoding.

Outputs:
  reports/00_data_inventory.md
  results/schema.json
"""
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
REPORTS = ROOT / "reports"
RESULTS = ROOT / "results"
REPORTS.mkdir(exist_ok=True)
RESULTS.mkdir(exist_ok=True)

FILES = {
    "LNPDB_vitro": DATA / "LNPDB_vitro.csv",
    "LNPDB_vivo": DATA / "LNPDB_vivo.csv",
    "Original_LNPDB": DATA / "Original_LNPDB.csv",
    "molea": DATA / "molea.csv",
}


def load(path):
    return pd.read_csv(path, low_memory=False)


def profile_dataframe(df, name, max_categories=8):
    lines = []
    lines.append(f"### `{name}`\n")
    lines.append(f"- Rows: **{len(df):,}**, Columns: **{df.shape[1]}**\n")
    lines.append("\n| # | Column | dtype | n_missing | %missing | n_unique | top values (freq) |")
    lines.append("|---|---|---|---|---|---|---|")
    for i, col in enumerate(df.columns):
        s = df[col]
        n_missing = int(s.isna().sum())
        pct_missing = 100 * n_missing / len(df) if len(df) else 0.0
        n_unique = int(s.nunique(dropna=True))
        top_str = ""
        # categorical-looking: object dtype or low-cardinality numeric
        is_categorical_like = (s.dtype == object) or (n_unique <= 30 and s.dtype != float)
        if is_categorical_like and n_unique > 0:
            vc = s.value_counts(dropna=True).head(5)
            top_str = "; ".join(f"{str(k)[:40]} ({v})" for k, v in vc.items())
        lines.append(
            f"| {i} | `{col}` | {s.dtype} | {n_missing:,} | {pct_missing:.1f}% | {n_unique:,} | {top_str} |"
        )
    return "\n".join(lines) + "\n"


def col_candidates(df, keywords):
    """Return column names containing any keyword as a substring, but not embedded
    inside a longer run of letters (so 'lab' matches 'Model_label' but not 'BalabanJ'
    or 'LabuteASA'). Non-letter characters (underscore, digits, case changes) count
    as boundaries."""
    import re

    out = []
    for c in df.columns:
        cl = c.lower()
        for k in keywords:
            for m in re.finditer(re.escape(k), cl):
                start, end = m.start(), m.end()
                before_ok = start == 0 or not cl[start - 1].isalpha()
                # a keyword ending in "_" (prefix-style, e.g. "hl_") already supplies
                # its own trailing boundary, so don't also require a non-letter after it
                after_ok = k.endswith("_") or end == len(cl) or not cl[end].isalpha()
                if before_ok and after_ok:
                    out.append(c)
                    break
            else:
                continue
            break
    return out


def main():
    report = []
    report.append("# Stage 0 — Data Inventory\n")
    report.append(
        "Generated by `scripts/stage00_inspect.py`. Read-only inspection of the four raw files "
        "in `data/`; no filtering or transformation happens in this stage.\n"
    )

    dfs = {}
    for name, path in FILES.items():
        if not path.exists():
            print(f"FATAL: expected data file missing: {path}", file=sys.stderr)
            sys.exit(1)
        dfs[name] = load(path)
        print(f"Loaded {name}: {dfs[name].shape[0]:,} rows x {dfs[name].shape[1]} cols from {path.name}")

    # ---- Per-file profile ----
    report.append("## 1. Per-file profile\n")
    for name, df in dfs.items():
        report.append(profile_dataframe(df, name))
        report.append("\n")

    # ---- Column role discovery ----
    report.append("## 2. Column-role discovery (heuristic candidates)\n")
    role_keywords = {
        "ionizable_lipid_smiles": ["il_smiles", "smiles"],
        "source_label": ["experiment_id", "publication", "pmid", "source"],
        "delivery_readout": ["experiment_value", "value", "mtp", "delivery", "luminescence", "expression", "abundance", "efficiency"],
        "readout_method": ["experiment_method", "method", "assay"],
        "cell_line": ["model_type", "cell", "tissue"],
        "cargo": ["cargo"],
        "route": ["route"],
        "model_invitro_invivo": ["model"],
        "formulation": ["hl_", "chl_", "peg_", "fifthcomponent", "molratio"],
    }
    schema = {}
    for name, df in dfs.items():
        schema[name] = {"n_rows": int(len(df)), "n_cols": int(df.shape[1]), "columns": list(df.columns), "roles": {}}
        report.append(f"### `{name}`\n")
        for role, kws in role_keywords.items():
            cands = col_candidates(df, kws)
            schema[name]["roles"][role] = cands
            report.append(f"- **{role}**: {cands if cands else 'NONE FOUND'}")
        report.append("\n")

    # ---- Partition check: vitro + vivo vs Original ----
    report.append("## 3. Partition check: LNPDB_vitro ∪ LNPDB_vivo vs Original_LNPDB\n")
    orig = dfs["Original_LNPDB"]
    vitro = dfs["LNPDB_vitro"]
    vivo = dfs["LNPDB_vivo"]

    report.append(f"- `Original_LNPDB.csv` rows: **{len(orig):,}**")
    report.append(f"- `LNPDB_vitro.csv` rows: **{len(vitro):,}**")
    report.append(f"- `LNPDB_vivo.csv` rows: **{len(vivo):,}**")
    report.append(f"- vitro + vivo = **{len(vitro) + len(vivo):,}**")
    report.append(f"- vitro + vivo - Original = **{len(vitro) + len(vivo) - len(orig):,}**\n")

    # column overlap
    orig_cols = set(orig.columns)
    vitro_cols = set(vitro.columns)
    vivo_cols = set(vivo.columns)
    report.append(f"- Columns only in `Original_LNPDB` (not vitro): {sorted(orig_cols - vitro_cols)}")
    report.append(f"- Columns only in `LNPDB_vitro` (not Original): {sorted(vitro_cols - orig_cols)}")
    report.append(f"- Columns only in `Original_LNPDB` (not vivo): {sorted(orig_cols - vivo_cols)}")
    report.append(f"- Columns only in `LNPDB_vivo` (not Original): {sorted(vivo_cols - orig_cols)}\n")

    # Try a row-identity check using a composite key of common columns, since there's
    # no guaranteed single-row primary key.
    common_cols = sorted(orig_cols & vitro_cols & vivo_cols)
    report.append(f"- Common columns across all three ({len(common_cols)}): {common_cols}\n")

    if "Model" in orig.columns:
        model_counts = orig["Model"].value_counts(dropna=False)
        report.append("Original_LNPDB `Model` column value counts:\n")
        report.append("```\n" + model_counts.to_string() + "\n```\n")

    # Attempt exact row-content matching via a hash of common columns, if feasible.
    # Exclude row-unique identifier columns (assigned per-file, not content) which
    # would otherwise guarantee zero overlap regardless of actual row content.
    id_like_cols = {"Index", "LNP_ID", "Formulation_ID"}
    content_cols = [c for c in common_cols if c not in id_like_cols]
    report.append(f"- Excluded row-identifier columns from content hash: {sorted(id_like_cols & set(common_cols))}")
    report.append(f"- Content columns used for row-hash ({len(content_cols)}): {content_cols}\n")
    # has_ester/has_carbonate/has_disulfide are typed inconsistently across files
    # (native bool in Original/vivo vs string "TRUE"/"FALSE"/"1"/"0" in vitro, the
    # latter from the AC_2025 merge). Normalize to a canonical string before hashing
    # so the row-content comparison reflects real content, not serialization dtype.
    bool_like_cols = [c for c in content_cols if c.startswith("has_")]
    report.append(f"- Normalizing boolean-like columns before hashing (dtype differs across files): {bool_like_cols}")

    def normalize_bool_like(series):
        mapping = {"true": "True", "false": "False", "1": "True", "0": "False", "1.0": "True", "0.0": "False"}
        return series.astype(str).str.strip().str.lower().map(lambda v: mapping.get(v, v))

    # Any numeric column becomes int64 when a file happens to have zero missing
    # values in it and float64 when another file has NaNs in the same column
    # (pandas' read_csv dtype inference) — e.g. "24969323" vs "24969323.0". Coerce
    # every numeric-dtype column to float64 before stringifying so this dtype
    # accident doesn't register as a content difference.
    def row_hash_series_impl(df, cols, bool_cols):
        sub = df[cols].copy()
        for c in cols:
            if c in bool_cols:
                continue
            if pd.api.types.is_numeric_dtype(sub[c]):
                sub[c] = sub[c].astype(float)
        for bc in bool_cols:
            sub[bc] = normalize_bool_like(sub[bc])
        sub = sub.astype(str)
        return pd.util.hash_pandas_object(sub, index=False)

    if content_cols:
        try:
            def row_hash_series(df, cols):
                return row_hash_series_impl(df, cols, bool_like_cols)

            orig_hash = row_hash_series(orig, content_cols)
            vitro_hash = row_hash_series(vitro, content_cols)
            vivo_hash = row_hash_series(vivo, content_cols)

            orig_counts = orig_hash.value_counts()
            vitro_counts = vitro_hash.value_counts()
            vivo_counts = vivo_hash.value_counts()
            combined_counts = vitro_counts.add(vivo_counts, fill_value=0)

            orig_hashes = set(orig_counts.index)
            combined_hashes = set(combined_counts.index)

            report.append(f"- Distinct content-row-hashes: Original={len(orig_hashes):,}, vitro∪vivo={len(combined_hashes):,}")
            report.append(f"- Content-hashes in Original but not in vitro∪vivo: {len(orig_hashes - combined_hashes):,}")
            report.append(f"- Content-hashes in vitro∪vivo but not in Original: {len(combined_hashes - orig_hashes):,}")

            # multiplicity check on the intersection (does count per distinct row match?)
            shared = orig_hashes & combined_hashes
            mismatched_mult = sum(
                1 for h in shared if orig_counts.get(h, 0) != combined_counts.get(h, 0)
            )
            report.append(f"- Shared distinct rows with matching Original vs vitro∪vivo file: multiplicity mismatches on {mismatched_mult:,} / {len(shared):,} shared distinct rows\n")
        except Exception as e:
            report.append(f"- Row-hash comparison failed: {e}\n")

    # ---- molea.csv endpoint encoding ----
    report.append("## 4. `molea.csv` endpoint encoding\n")
    molea = dfs["molea"]
    hep_cols = [c for c in molea.columns if "hepatocyte" in c.lower()]
    chon_cols = [c for c in molea.columns if "chondrocyte" in c.lower()]
    report.append(f"- Hepatocyte-related columns: {hep_cols}")
    report.append(f"- Chondrocyte-related columns: {chon_cols}")
    source_like = col_candidates(molea, ["source", "publication", "pmid", "experiment", "lab", "study"])
    report.append(f"- Source/publication-like columns: {source_like if source_like else 'NONE FOUND — molea appears to be a single source'}")
    smiles_like = col_candidates(molea, ["smiles"])
    report.append(f"- SMILES-like columns: {smiles_like}")
    markush_like = col_candidates(molea, ["markush", "code", "linker", "head", "tail"])
    report.append(f"- Markush/component-code columns: {markush_like}\n")

    schema["molea"] = schema.get("molea", {})
    schema["molea"]["endpoint_columns"] = {"hepatocyte": hep_cols, "chondrocyte": chon_cols}
    schema["molea"]["source_columns"] = source_like
    schema["molea"]["smiles_columns"] = smiles_like

    # ---- Authoritative single-column resolution ----
    # The "roles" block above lists heuristic keyword-match CANDIDATES for review.
    # This "resolved" block is the single, unambiguous column-per-role mapping that
    # every downstream stage imports (per dataset). Chosen by inspecting the actual
    # profiled values above, not by the keyword heuristic. `null` = role genuinely
    # absent in that dataset (recorded explicitly, not silently skipped).
    lnpdb_resolved = {
        "ionizable_lipid_smiles": "IL_SMILES",
        "ionizable_lipid_protonated_smiles": "IL_protonated_SMILES",
        "ionizable_lipid_name": "IL_name",
        "source_label": "Experiment_ID",
        "publication_pmid": "Publication_PMID",
        "publication_link": "Publication_link",
        "delivery_readout": "Experiment_value",
        "readout_method": "Experiment_method",
        "readout_batching": "Experiment_batching",
        "cell_or_animal_model": "Model_type",
        "model_target": "Model_target",
        "cargo": "Cargo",
        "cargo_type": "Cargo_type",
        "route": "Route_of_administration",
        "invitro_invivo": "Model",
        "dose": "Dose_ug_nucleicacid",
        "row_id": "LNP_ID",
        "formulation_id": "Formulation_ID",
        "helper_lipid_name": "HL_name",
        "helper_lipid_smiles": "HL_SMILES",
        "helper_lipid_molratio": "HL_molratio",
        "cholesterol_name": "CHL_name",
        "cholesterol_smiles": "CHL_SMILES",
        "cholesterol_molratio": "CHL_molratio",
        "peg_lipid_name": "PEG_name",
        "peg_lipid_smiles": "PEG_SMILES",
        "peg_lipid_molratio": "PEG_molratio",
        "fifth_component_name": "fifthcomponent_name",
        "fifth_component_smiles": "fifthcomponent_SMILES",
        "fifth_component_molratio": "fifthcomponent_molratio",
        "ionizable_lipid_molratio": "IL_molratio",
        "il_head_smiles": "IL_head_SMILES",
        "il_linker_smiles": "IL_linker_SMILES",
        "il_tail1_smiles": "IL_tail1_SMILES",
        "il_tail2_smiles": "IL_tail2_SMILES",
    }
    resolved = {
        "LNPDB_vitro": dict(lnpdb_resolved, _note="Model_target is mostly 'in_vitro'/'lung_epithelium' here — not a meaningful tissue target for in-vitro rows, unlike in-vivo."),
        "LNPDB_vivo": dict(lnpdb_resolved, _note="Model_type holds mouse strain (not cell line) here; Model_target holds the dosed tissue (liver/muscle/spleen/...)."),
        "Original_LNPDB": dict(lnpdb_resolved, _note="Reference only — not used for analysis, per project convention (Stage 0 uses it solely to verify the vitro/vivo partition)."),
        "molea": {
            "ionizable_lipid_smiles": "smiles",
            "ionizable_lipid_name": None,
            "source_label": None,
            "publication_pmid": None,
            "publication_link": None,
            "delivery_readout_hepatocyte": "mTP_(Log2)_Hepatocyte",
            "delivery_readout_chondrocyte": "mTP_(Log2)_Chondrocyte",
            "delivery_readout_difference": "mTP_Difference",
            "readout_method": None,
            "cell_or_animal_model": None,
            "model_target": None,
            "cargo": None,
            "cargo_type": None,
            "route": None,
            "invitro_invivo": None,
            "dose": None,
            "row_id": None,
            "formulation_id": None,
            "component_code": "Markush code",
            "_note": (
                "molea is a single-source combinatorial screen (Markush code = Linker x Head x tail "
                "enumeration). No source/publication column: per CLAUDE.md project decision, treat as "
                "one source, two endpoints (hepatocyte, chondrocyte). mTP_Difference is a derived "
                "selectivity contrast, not an independently poolable readout. No formulation/cargo/route "
                "columns exist (single fixed experimental context; 800+ desc_* columns are RDKit/Mordred-"
                "style molecular descriptors of `smiles`, not experimental metadata)."
            ),
        },
    }
    for name in resolved:
        schema[name]["resolved"] = resolved[name]

    report.append("## 5. Resolved schema (authoritative — this is what Stage 1+ imports)\n")
    for name, rmap in resolved.items():
        report.append(f"### `{name}`\n")
        note = rmap.get("_note", "")
        if note:
            report.append(f"> {note}\n")
        report.append("| role | column |")
        report.append("|---|---|")
        for role, col in rmap.items():
            if role == "_note":
                continue
            report.append(f"| {role} | {'`' + col + '`' if col else '**MISSING**'} |")
        report.append("\n")

    # ---- Write outputs ----
    (REPORTS / "00_data_inventory.md").write_text("\n".join(str(x) for x in report))
    with open(RESULTS / "schema.json", "w") as f:
        json.dump(schema, f, indent=2, default=str)

    print("\nWrote reports/00_data_inventory.md and results/schema.json")
    print("\n--- SUMMARY ---")
    for name, df in dfs.items():
        print(f"{name}: {df.shape[0]:,} rows x {df.shape[1]} cols")


if __name__ == "__main__":
    main()
